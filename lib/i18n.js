function translator(lang) {
  const dict = STRINGS[lang] || STRINGS.en;
  // Extra args fill {0}, {1}, ... placeholders in the string -- needed
  // because a fixed English prefix/suffix (e.g. "Explore " + category)
  // can't become correct German word order on its own: "Explore
  // Requirements Engineering" needs to become "Requirements Engineering
  // entdecken", with the verb moved to the end, not just a translated
  // "Explore" stuck back on the front.
  return (key, ...args) => {
    let str = dict[key] || STRINGS.en[key] || key;
    args.forEach((arg, i) => { str = str.split(`{${i}}`).join(arg); });
    return str;
  };
}

